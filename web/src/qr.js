/**
 * @param {string} text ASCII/Latin-1 text (a URL, here). Encoded byte for
 *   byte: nothing in this product's payload needs multi-byte characters.
 * @returns {{
 *   version: number, size: number, mask: number, eccLevel: 'M',
 *   modules: boolean[][], isFunction: boolean[][], codewords: number[]
 * }}
 */
export function encodeQR(text) {
  const bytes = Array.from(text, (ch) => ch.charCodeAt(0) & 0xff);
  const version = chooseVersion(bytes.length);
  if (!version) throw new Error('Text is too long for a version 1-10 QR code at error correction level M.');

  const dataCodewords = buildCodewords(version, bytes);
  const codewords = interleave(version, dataCodewords);
  const codewordBits = codewordsToBits(codewords, REMAINDER_BITS[version]);

  const size = symbolSize(version);
  const modules = makeGrid(size, false);
  const isFunction = makeGrid(size, false);

  drawFinderPattern(modules, isFunction, 0, 0, size);
  drawFinderPattern(modules, isFunction, size - 7, 0, size);
  drawFinderPattern(modules, isFunction, 0, size - 7, size);
  placeAlignmentPatterns(modules, isFunction, version);
  placeTimingPatterns(modules, isFunction, size);
  reserveFormatArea(isFunction, size);
  reserveVersionArea(isFunction, size, version);
  isFunction[size - 8][8] = true; // the fixed dark module

  placeData(modules, isFunction, size, codewordBits);

  let bestMask = 0;
  let bestScore = Infinity;
  let bestGrid = null;
  for (let mask = 0; mask < 8; mask += 1) {
    const candidate = applyMask(modules, isFunction, size, MASK_FUNCTIONS[mask]);
    const score = totalPenalty(candidate, size);
    if (score < bestScore) {
      bestScore = score;
      bestMask = mask;
      bestGrid = candidate;
    }
  }

  writeFormatBits(bestGrid, bestMask);
  writeVersionBits(bestGrid, version);

  return { version, size, mask: bestMask, eccLevel: 'M', modules: bestGrid, isFunction, codewords };
}

