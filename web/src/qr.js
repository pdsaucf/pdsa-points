// THE QUIET ZONE IS FOUR MODULES, NOT TWO. ISO/IEC 18004 requires a clear
// margin of four modules on every side of a QR symbol (two is the Micro QR
// figure, and is the easy mistake). A narrower margin still decodes from a
// clean raster, which is exactly why getting this wrong survives testing: it
// fails later, on a printed sheet where something is placed near the code, on
// a coloured background, or at the angle somebody actually holds a phone at.
const QUIET_ZONE = 4;

const SVG_NS = 'http://www.w3.org/2000/svg';

/**
 * The QR code as an inline <svg>, built with createElementNS the way
 * ui.js's chevron() is: no innerHTML anywhere in this codebase, and an SVG
 * assembled with the plain HTML createElement lands in the wrong namespace
 * and renders as nothing.
 *
 * One <path> carries every dark module, rather than one <rect> per module:
 * a version 10 code is 57x57 modules, and a wall of three thousand rect
 * elements is not something this dialog needs to pay for.
 */
export function qrToSvgElement(qr, { pixelSize = 240, margin = QUIET_ZONE } = {}) {
  const { size, modules } = qr;
  const total = size + margin * 2;

  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', `0 0 ${total} ${total}`);
  svg.setAttribute('width', String(pixelSize));
  svg.setAttribute('height', String(pixelSize));
  svg.setAttribute('role', 'img');
  svg.setAttribute('aria-label', 'Check-in QR code');
  svg.setAttribute('shape-rendering', 'crispEdges');

  const background = document.createElementNS(SVG_NS, 'rect');
  background.setAttribute('x', '0');
  background.setAttribute('y', '0');
  background.setAttribute('width', String(total));
  background.setAttribute('height', String(total));
  background.setAttribute('fill', '#fff');
  svg.append(background);

  let d = '';
  for (let r = 0; r < size; r += 1) {
    for (let c = 0; c < size; c += 1) {
      if (!modules[r][c]) continue;
      const x = c + margin;
      const y = r + margin;
      d += `M${x},${y}h1v1h-1z`;
    }
  }
  const path = document.createElementNS(SVG_NS, 'path');
  path.setAttribute('d', d);
  path.setAttribute('fill', '#000');
  svg.append(path);

  return svg;
}

/** The same code drawn onto a <canvas>, for the PNG download. */
export function qrDrawToCanvas(qr, canvas, { pixelSize = 512, margin = QUIET_ZONE } = {}) {
  const { size, modules } = qr;
  const total = size + margin * 2;
  const scale = Math.max(1, Math.floor(pixelSize / total));
  const drawn = total * scale;

  canvas.width = drawn;
  canvas.height = drawn;
  const ctx = canvas.getContext('2d');
  ctx.fillStyle = '#fff';
  ctx.fillRect(0, 0, drawn, drawn);
  ctx.fillStyle = '#000';
  for (let r = 0; r < size; r += 1) {
    for (let c = 0; c < size; c += 1) {
      if (!modules[r][c]) continue;
      ctx.fillRect((c + margin) * scale, (r + margin) * scale, scale, scale);
    }
  }
  return canvas;
}
